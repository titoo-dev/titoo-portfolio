function isPair(value: object): value is T<unknown> {
  const keys = Object.keys(value);
  return keys.length === 2 && "fr" in value && "en" in value;
}

function resolve<V>(value: V, locale: Locale): Resolved<V> {
  if (Array.isArray(value)) {
    return value.map((v) => resolve(v, locale)) as Resolved<V>;
  }
  if (value && typeof value === "object") {
    if (isPair(value)) return value[locale] as Resolved<V>;
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, resolve(v, locale)]),
    ) as Resolved<V>;
  }
  return value as Resolved<V>;
}

export type Content = {
  PROFILE: Resolved<typeof PROFILE>;
  careers: Career[];
  projects: Project[];
  services: Service[];
  stack: StackGroup[];
};

const cache = new Map<Locale, Content>();

/** Every piece of portfolio data, in one language. */
export function getContent(locale: Locale): Content {
  let content = cache.get(locale);
  if (!content) {
    content = resolve(
      { PROFILE, careers, projects, services, stack },
      locale,
    ) as Content;
    cache.set(locale, content);
  }
  return content;
}

/** Project slugs are shared by every locale. */
export const projectSlugs = projects.map((p) => p.slug);

export function getProject(locale: Locale, slug: string): Project | undefined {
  return getContent(locale).projects.find((p) => p.slug === slug);
}
